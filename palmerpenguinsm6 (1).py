# Math import for function
import math

# Define a function to calculate a percentage
def calculate_percentage(count, total):
    return count / total * 100

# Define a second function to get the size of the species
def classify_species(percent):
    if percent < 25:
        return "small"
    elif percent < 40:
        return "medium"
    else:
        return "large"

# Define a third function to get the position of the species
def get_position_description(selected_species, largest_species, smallest_species):
    if selected_species == largest_species:
        return "largest"
    elif selected_species == smallest_species:
        return "smallest"
    else:
        return "middle sized"

# Define a fourth function to display the species statistics
def display_species_stats(names, counts, percentages):
    for index, species in enumerate(names):
        print(f"{species}: {counts[index]} "
              f"({percentages[index]:.2f}%)")

# Define a function to display penguin observations
def display_penguin_observations(sample_number, species, bill_length, bill_depth, body_mass, sex):
    print("Penguin Observation:")
    print(f"  {'Sample Number':<15}: {sample_number}")
    print(f"  {'Species':<15}: {species}")
    print(f"  {'Bill Length':<15}: {bill_length}")
    print(f"  {'Bill Depth':<15}: {bill_depth}")
    print(f"  {'Body Mass':<15}: {body_mass}")
    print(f"  {'Sex':<15}: {sex}")
    print()

# instructor-provided function
# copy and paste into your solution
def read_penguin_row(row_number):
    penguin_row = ""

    # open the CSV file and skip the header row
    with open("PalmerPenguins.csv", "r") as penguin_file:
        penguin_file.readline()

        current_row = 1

        # search for the requested data row
        for row in penguin_file:
            if current_row == row_number:
                penguin_row = row.strip()
                break

            current_row += 1

    # return the requested row as a string
    return penguin_row

# Constants representing the species and count
SP_CHINSTRAP = "Chinstrap"
SP_GENTOO = "Gentoo"
SP_ADELIE = "Adelie"
NUM_CHINSTRAP = 68
NUM_GENTOO = 123
NUM_ADELIE = 151

# Define the main function
def main():
    # Lists containing related penguin data
    species_names = [SP_CHINSTRAP, SP_GENTOO, SP_ADELIE]
    species_counts = [NUM_CHINSTRAP, NUM_GENTOO, NUM_ADELIE]

    # Calculate dataset statistics
    total_species = len(species_names)
    largest_count = max(species_counts)
    smallest_count = min(species_counts)
    largest_index = species_counts.index(largest_count)
    smallest_index = species_counts.index(smallest_count)
    largest_species = species_names[largest_index]
    smallest_species = species_names[smallest_index]
    total_penguins = sum(species_counts)
    average_penguins = total_penguins / total_species

    # Calculate the percentage for each species
    chinstrap_percent = calculate_percentage(
        species_counts[0], total_penguins)
    gentoo_percent = calculate_percentage(
        species_counts[1], total_penguins)
    adelie_percent = calculate_percentage(
        species_counts[2], total_penguins)

    species_percentages = [
        chinstrap_percent,
        gentoo_percent,
        adelie_percent
    ]

    average_penguins_rounded_up = math.ceil(average_penguins)

    # Output the species names with introductory text
    print("Introducing the Palmer Penguins:")
    print(f"\t{species_names[0]}!")
    print(f"\t{species_names[1]}!")
    print("and last but not least. . .")
    print(f"\t{species_names[2]}!")
    print()

    print(f"There are a total of {total_species} penguin species in this dataset.")
    print()

    # Display the total number of penguins alongside the average
    print(f"There are a total of {total_penguins} penguins in the dataset")
    print(f"The average number of penguins per species is ({average_penguins:.1f}).")
    print(f"The average rounded up is {average_penguins_rounded_up} penguins.")
    print()

    # Display the species counts alongside their percentages
    display_species_stats(
        species_names, species_counts, species_percentages)

    print()

    print(f"The species with the most observations is {largest_species} "
          f"with {largest_count} penguins.")
    print(f"The species with the least observations is {smallest_species} "
          f"with {smallest_count} penguins.")
    print()

    # Retrieve the first penguin observation
    penguin_row = read_penguin_row(1)
    print("Sample dataset row:")
    print(penguin_row)
    print()

    # Split the row into individual values
    penguin_data = penguin_row.split(",")

    # Extract and convert the values
    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    bill_length = float(penguin_data[2])
    bill_depth = float(penguin_data[3])
    body_mass = int(penguin_data[4])
    sex = penguin_data[5]

    # Display the first observation
    display_penguin_observations(
        sample_number, species,
        bill_length, bill_depth,
        body_mass, sex
    )

    print()

    # Retrieve the second penguin observation
    penguin_row = read_penguin_row(2)
    print("Sample dataset row:")
    print(penguin_row)
    print()

    # Split the row into individual values
    penguin_data = penguin_row.split(",")

    # Extract and convert the values
    sample_number = int(penguin_data[0])
    species = penguin_data[1]
    bill_length = float(penguin_data[2])
    bill_depth = float(penguin_data[3])
    body_mass = int(penguin_data[4])
    sex = penguin_data[5]

    # Display the second observation
    display_penguin_observations(
        sample_number, species,
        bill_length, bill_depth,
        body_mass, sex
    )

    # Explore a species using a sentinel-controlled while loop
    valid_selections = 0

    print("Explore a species:")
    species_choice = input("Enter Chinstrap, Gentoo, Adelie, or Done: ")

    while species_choice != "Done":
        if species_choice not in species_names:
            print(species_choice,
                  "is not one of the species in this dataset")
        else:
            # Determine the selected species
            valid_selections += 1

            if species_choice == species_names[0]:
                selected_index = 0
            elif species_choice == species_names[1]:
                selected_index = 1
            else:
                selected_index = 2

            selected_species = species_names[selected_index]
            selected_count = species_counts[selected_index]
            selected_percent = species_percentages[selected_index]
            size_category = classify_species(selected_percent)

            # Determine its position
            position_description = get_position_description(
                selected_species, largest_species, smallest_species)

            # Compare with the average
            average_position = (
                "above" if selected_count > average_penguins else "below")

            # Print results only for a valid species
            print(f"{species_choice} has {selected_count} observations, "
                  f"representing {selected_percent:.2f}% of the dataset.")
            print(f"{species_choice} is classified as a "
                  f"{size_category} species group.")
            print(f"{species_choice} is the "
                  f"{position_description} species group.")
            print(f"The penguin count is {average_position} average.")
            print(f"Its observation count is {average_position} the dataset "
                  f"average of {average_penguins}")
            print()

        species_choice = input(
            "Enter Chinstrap, Gentoo, Adelie, or Done: ")

    # Display the final summary after the loop ends
    print(f"You explored {valid_selections} valid species selections.")

# Call the main function to run the program
main()

